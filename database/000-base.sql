-- Churrasco na Marmita — tabelas base para um projeto NOVO (staging/local).
-- NÃO rode este arquivo em produção depois do cutover: ele recria políticas
-- permissivas que o 005-rls-cutover.sql remove.
-- Ordem em um banco vazio: 000 -> 001 -> 002 -> 003 -> 004 (e 005 para simular o cutover).

create table if not exists status (
  id bigint primary key default 1,
  "isOpen" boolean not null default true
);
insert into status (id, "isOpen") values (1, true) on conflict (id) do nothing;

create table if not exists config (
  id bigint primary key default 1,
  nome_loja text,
  descricao_loja text,
  telefone text,
  endereco text,
  instagram text,
  logo text,
  banner text,
  atualizado_em timestamptz default now()
);
insert into config (id) values (1) on conflict (id) do nothing;

create table if not exists produtos (
  id bigint generated by default as identity primary key,
  nome text not null,
  preco numeric not null default 0,
  descricao text,
  imagem text,
  categoria text default 'meal',
  ativo boolean default true,
  ordem int default 0,
  criado_em timestamptz default now()
);

create table if not exists pedidos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  cliente text,
  telefone text,
  bairro text,
  endereco text,
  pagamento text,
  observacao text,
  itens jsonb default '[]'::jsonb,
  subtotal numeric(10,2) default 0,
  frete numeric(10,2) default 0,
  total numeric(10,2) default 0,
  finalizado boolean not null default false,
  finalizado_por text,
  finalizado_em timestamptz,
  impresso boolean not null default false,
  impresso_por text,
  impresso_em timestamptz,
  cancelado boolean not null default false,
  motivo_cancelamento text,
  cancelado_por text,
  cancelado_ip text,
  cancelado_em timestamptz
);

-- Políticas permissivas de base. O 005-rls-cutover.sql as substitui.
alter table status enable row level security;
drop policy if exists anon_all_status on status;
create policy anon_all_status on status for all using (true) with check (true);

alter table config enable row level security;
drop policy if exists anon_all_config on config;
create policy anon_all_config on config for all using (true) with check (true);

alter table produtos enable row level security;
drop policy if exists anon_all_produtos on produtos;
create policy anon_all_produtos on produtos for all using (true) with check (true);

alter table pedidos enable row level security;
drop policy if exists anon_all_pedidos on pedidos;
create policy anon_all_pedidos on pedidos for all using (true) with check (true);
