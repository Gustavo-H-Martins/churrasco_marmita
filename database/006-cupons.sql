create table if not exists cupons (
  id bigint generated by default as identity primary key,
  codigo text not null unique check (codigo = upper(codigo)),
  percentual numeric(5,2) not null check (percentual > 0 and percentual <= 100),
  ativo boolean not null default true,
  validade_inicio date,
  validade_fim date,
  uso_maximo int check (uso_maximo is null or uso_maximo > 0),
  usos int not null default 0,
  criado_em timestamptz not null default now()
);

alter table pedidos
  add column if not exists cupom text,
  add column if not exists desconto numeric(10,2) not null default 0;

alter table cupons enable row level security;
drop policy if exists cupons_admin_all on cupons;
create policy cupons_admin_all on cupons for all
  using (eh_admin()) with check (eh_admin());

create or replace function public.validar_cupom(p_codigo text)
returns table (codigo text, percentual numeric)
language sql stable security definer set search_path = public as $$
  select c.codigo, c.percentual
  from cupons c
  where upper(c.codigo) = upper(trim(p_codigo))
    and c.ativo
    and (c.validade_inicio is null or c.validade_inicio <= current_date)
    and (c.validade_fim is null or c.validade_fim >= current_date)
    and (c.uso_maximo is null or c.usos < c.uso_maximo)
  limit 1;
$$;
revoke execute on function public.validar_cupom(text) from public;
grant execute on function public.validar_cupom(text) to anon, authenticated;

create or replace function public.incrementar_uso_cupom()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.cupom is not null and trim(new.cupom) <> '' then
    update cupons set usos = usos + 1
    where upper(codigo) = upper(trim(new.cupom));
  end if;
  return new;
end;
$$;

drop trigger if exists on_pedido_cupom on pedidos;
create trigger on_pedido_cupom
  after insert on pedidos
  for each row execute function public.incrementar_uso_cupom();
